import assert from 'node:assert/strict'
import fs from 'node:fs'

const modal = fs.readFileSync('pages/report/components/CheckItemModal.vue', 'utf8')
const grid = fs.readFileSync('pages/report/components/MediaGrid.vue', 'utf8')
const detail = fs.readFileSync('pages/report/detail.vue', 'utf8')

assert.match(detail, /:show-check-point-upload="showCheckPointUpload"/, 'modal should receive the selected inspection plan flag')
assert.match(detail, /const plans = Array\.isArray\(planData\.value\?\.inspectionPlans\)/, 'visibility should use inspectionPlans')
assert.match(detail, /Number\(.*goodsFlag.*\)\s*===\s*9/, 'only goodsFlag 9 should enable the upload')
assert.match(modal, /v-if="showCheckPointUpload"[\s\S]*?上传检查点图片/, 'upload button should be conditional')
assert.match(modal, /重置检查点[\s\S]*?上传检查点图片/, 'upload button should follow reset')
assert.match(modal, /showActionSheet\([\s\S]*?拍照[\s\S]*?从相册选择/, 'button should offer camera and album')
assert.match(modal, /pickCheckPointImage\(/, 'button should invoke the dedicated picker')
assert.match(grid, /sourceType:\s*options\.sourceType\s*\|\|\s*\["camera"\]/, 'picker should support camera and album without changing media library default')
assert.match(grid, /mediaType:\s*options\.mediaType\s*\|\|\s*\["image",\s*"video"\]/, 'checkpoint picker should request images only')
assert.match(grid, /emit\("add-check-point"/, 'checkpoint images should be emitted separately')
assert.match(detail, /@add-check-point-media="handleCheckPointMediaAdd"/, 'detail should handle checkpoint media')
assert.match(detail, /handleCheckPointMediaAdd\([\s\S]*?'checkPoint'/, 'checkpoint records should use checkPoint bizType')
assert.match(detail, /bizType:\s*oldPhoto\?\.bizType\s*\|\|\s*'checkResult'/, 'editing should preserve the photo bizType')
assert.match(modal, /:photos="mediaPhotos"/, 'media library should display ordinary photos only')
assert.match(modal, /上传检查点图片[\s\S]*?:photos="checkPointPhotos"/, 'checkpoint photos should appear below the upload button')
assert.match(modal, /v-if="showCheckPointUpload && checkPointPhotos\.length"[^>]*>\s*<view class="section-title">\{\{ t\('检查点图片'\) \}\}<\/view>/, 'checkpoint gallery should show its title only when photos exist')
assert.match(modal, /:hide-add="true"/, 'checkpoint gallery should not duplicate the add button')
assert.match(modal, /getOriginalPhotoIndex\(/, 'gallery actions should target the original photo index')
assert.match(modal, /:photos="mediaPhotos"[\s\S]*?@sorted="onPhotosSorted"/, 'sort should exclude checkpoint photos')
assert.match(detail, /const allMedia = getMediaPhotos\(/, 'batch move should exclude checkpoint photos')
assert.match(detail, /if \(p\.bizType\) entry\.bizType = p\.bizType/, 'local detail cache should retain the downloaded business type')
